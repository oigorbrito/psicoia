export const LOCALE_STORAGE_KEY = "mindcare.locale";
export const SUPPORTED_LOCALES = ["en", "pt-BR"];

export function getLocale() {
  const savedLocale = typeof localStorage !== "undefined" ? localStorage.getItem(LOCALE_STORAGE_KEY) : null;
  const locale = SUPPORTED_LOCALES.includes(savedLocale) ? savedLocale : "pt-BR";
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  return locale;
}

export function setLocale(locale) {
  const value = SUPPORTED_LOCALES.includes(locale) ? locale : "en";
  if (typeof localStorage !== "undefined") localStorage.setItem(LOCALE_STORAGE_KEY, value);
  if (typeof document !== "undefined") document.documentElement.lang = value;
  return value;
}

export function getOutputLanguage(locale = getLocale()) {
  return locale === "pt-BR" ? "Português (Brasil)" : "English";
}

export function t(message, locale = getLocale(), values = {}) {
  const sourceMessage = ZH_SOURCE_TO_EN[message] || message;
  if (locale !== "pt-BR") return interpolate(sourceMessage, values);
  const translated = PT_BR[sourceMessage] || sourceMessage;
  return interpolate(translated, values);
}

function interpolate(message, values) {
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}
